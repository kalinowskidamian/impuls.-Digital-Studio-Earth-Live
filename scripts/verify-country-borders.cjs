"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const html = fs.readFileSync("public/index.html", "utf8");
const code=html.slice(html.indexOf("function borderPaths("),html.indexOf("async function loadBorders("));
const calls=[],marks=[];
const globe={pathsData(paths){calls.push(paths);return this;}};
const context={state:{globe},performance:{mark(name){marks.push(name);}}};
vm.runInNewContext(code,context);
const topology={transform:{scale:[1,1],translate:[0,0]},arcs:[[[0,0],[1,2]],[[1,2],[3,4]]],objects:{countries:{geometries:[{arcs:[[0,1]]},{arcs:[[-1]]}]}}};
const paths=context.borderPaths(topology);
assert.deepEqual(JSON.parse(JSON.stringify(paths)),[{points:[[0,0],[1,2]]},{points:[[1,2],[4,6]]}]);
context.renderCountryBorders(globe,paths);
assert.equal(calls.length,1);
assert.equal(calls[0],paths);
assert.deepEqual(marks,["earth-live:borders-native"]);
context.renderCountryBorders({},paths);
assert.equal(calls.length,1);
assert.ok(html.includes('.pathPointAlt(.004).pathStroke(null)'));
assert.ok(html.includes('rgba(168,198,236,0.24)'));
console.log("QA PASS: native globe path layer, shared border deduplication and outline styling");
