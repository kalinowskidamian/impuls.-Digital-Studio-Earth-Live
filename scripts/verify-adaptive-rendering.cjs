"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const html=fs.readFileSync("public/index.html","utf8");
const source=html.slice(html.indexOf("function monitorGlobeQuality("),html.indexOf("function cancelHoverRelease("));
let ratio=1,callback,now=1,changes=[];
const renderer={getPixelRatio:()=>ratio,setPixelRatio:r=>{ratio=r;changes.push(r);}};
const globe={},state={globe,globeInView:true},document={hidden:false};
const context={window:{requestAnimationFrame:fn=>{callback=fn;}},state,document};
vm.runInNewContext(source,context);
context.monitorGlobeQuality(globe,renderer);
function frames(count,ms){for(let i=0;i<count;i++){now+=ms;callback(now);}}
frames(120,16.7);
assert.equal(ratio,1,"Fast desktop GPU retains original quality");
frames(30,80);
assert.equal(ratio,.75,"Slow frame pacing lowers framebuffer resolution");
frames(30,80);
assert.equal(ratio,.5625);
frames(100,80);
assert.ok(ratio>=.55,"Never exceed the lower quality bound");
document.hidden=true;
let pausedRatio=ratio;
frames(100,100);
assert.equal(ratio,pausedRatio,"Background frames do not affect quality");
document.hidden=false;
frames(900,16.7);
assert.equal(ratio,1,"Sustained fast rendering restores original quality");
assert.ok(changes.length>0);
console.log("QA PASS: adaptive pixel ratio, bounds, hidden tab and recovery");
